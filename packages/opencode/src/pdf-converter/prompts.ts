/**
 * 构建"公式图片"（公式中嵌入图形元素）的 bbox 提取 Prompt
 *
 * @param formulaFigureCount - 文本中检测到的 [FORMULA_FIGURE:ffig_N] 数量
 * @param retryHints - 上次失败原因列表
 */
export function buildFormulaFigurePrompt(
  formulaFigureCount: number = 1,
  retryHints?: string[],
): string {
  let hintsSection = "";
  if (retryHints && retryHints.length > 0) {
    const hintsLines = retryHints.map((h) => `  - ${h}`).join("\n");
    hintsSection = `⚠️ **上次提取发现问题，本次请特别注意修正**：\n${hintsLines}\n\n`;
  }

  return `${hintsSection}请识别这张 PDF 页面图片中**公式与图形混排**的区域坐标。

**背景说明**：
文本提取阶段已确认本页有 **${formulaFigureCount}** 个"公式+图形混排"区域——即公式/方程中嵌入了非标准数学符号的图形元素（线条、曲线、手绘图形等），无法用 LaTeX 转录的区域，必须整体截图。

**你的任务**：精确定位这 ${formulaFigureCount} 个公式图片区域的 bbox 坐标。

**什么是"公式+图形混排"区域**：
一行或多行公式中，等号的一侧（或两侧）包含**实际绘制的图形**（线条、圆圈、曲线等非标准数学记号），这些图形是公式不可分割的一部分（去掉图形后公式不完整）。

**⚠️ 多行公式必须作为一张整图截取（极其重要）**：
如果一个公式跨越**多行**，必须将**所有行**合并为**一个 bbox** 截取，生成一张包含全部内容的图片。**绝对不能**将每一行作为单独的图片截取！一个公式编号对应一个 ffig。
只要同一个显示公式里**任意一行**含有图形元素，后续即使只是纯字母、纯等号、纯表达式，也必须继续包含在同一个 bbox 内。

**⚠️ 不要截取以下内容**：
- 纯文字/纯公式区域（没有图形元素的公式，无论多复杂）
- 独立的插图（有图号、图名的图片——那些由普通图片提取流程处理）
- 表格

**bbox 坐标要求**：
- 格式：[x0, y0, x1, y1]，相对于页面的百分比（0~1 之间，保留 3 位小数）
- bbox 应精确覆盖整个公式+图形区域（包括公式文字和图形元素）
- 如果公式行前有公式编号（如 (4.54)），**包含编号在内**
- 如果同一编号公式分成多行，bbox 必须覆盖该编号对应的**整条公式**
- 不需要包含该区域上下的纯文字段落
- **不做宽高比限制**（公式图片可能很宽、很大或很长）

**输出格式**（JSON）：
\`\`\`json
{
  "formula_figures": [
    {
      "ffig_id": "ffig_1",
      "bbox": [0.065, 0.320, 0.935, 0.480],
      "description": "公式中嵌入了图形元素的区域描述"
    }
  ]
}
\`\`\`

**注意**：
- 只返回 JSON，不要有其他文字
- \`ffig_id\` 从 \`ffig_1\` 开始递增
- 没有找到公式图片区域时返回：\`{"formula_figures": []}\`
- **没有** figure_label、caption、caption_top_y、caption_bottom_y 字段（公式图片没有图名）`;
}

